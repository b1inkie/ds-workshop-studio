import { test, expect } from '@playwright/test';

test('bottom contact button opens information dialog with keyboard and close behavior', async ({ page }) => {
  await page.goto('/');
  const button = page.getByRole('button', { name: '联系与交流', exact: true });
  await expect(page.locator('.rail-bottom button').last()).toHaveAttribute('aria-label', '设置');
  expect(await page.locator('.rail-bottom button').evaluateAll(elements => elements.map(element => element.getAttribute('aria-label')))).toEqual(['查看迁移说明', '联系与交流', '信息', '设置']);
  await expect(button).toBeInViewport();
  await button.focus();
  await expect(page.getByRole('tooltip')).toHaveText('联系与交流');
  await page.keyboard.press('Enter');
  const dialog = page.getByRole('dialog', { name: '联系与交流', exact: true });
  await expect(dialog).toBeVisible();
  await expect(dialog).toContainText('饥荒mod制作技术交流');
  await expect(dialog).toContainText('623398781');
  const close = dialog.getByRole('button', { name: '关闭联系与交流' });
  await expect(dialog).toBeFocused();
  await expect(page.getByRole('tooltip')).toHaveCount(0);
  await page.keyboard.press('Shift+Tab');
  await expect(dialog.getByRole('button', { name: '知道了' })).toBeFocused();
  await page.keyboard.press('Tab');
  await expect(close).toBeFocused();
  await expect(page.getByRole('tooltip')).toHaveText('关闭联系与交流');
  await page.keyboard.press('Escape');
  await expect(page.getByRole('tooltip')).toHaveCount(0);
  await expect(dialog).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(dialog).toHaveCount(0);
  await expect(button).toBeFocused();
  await expect(page.getByRole('tooltip')).toHaveCount(0);
  await button.click();
  await expect(dialog).toBeFocused();
  await expect(page.getByRole('tooltip')).toHaveCount(0);
  expect(await button.evaluate(element => {
    const sibling = element.parentElement?.querySelector('[aria-label="信息"]');
    if (!sibling) throw new Error('Missing information button');
    const a = getComputedStyle(element); const b = getComputedStyle(sibling);
    return [a.backgroundColor, a.borderColor, a.width, a.height].join('|') === [b.backgroundColor, b.borderColor, b.width, b.height].join('|');
  })).toBe(true);
  await dialog.getByRole('button', { name: '知道了' }).click();
  await expect(dialog).toHaveCount(0);
  await expect(button).toBeFocused();
  await expect(page.getByRole('tooltip')).toHaveCount(0);
  await button.click();
  await page.locator('.modal-backdrop').click({ position: { x: 10, y: 10 } });
  await expect(dialog).toHaveCount(0);
  await expect(page.getByRole('tooltip')).toHaveCount(0);
  await page.mouse.move(600, 120);
  await button.hover();
  await expect(page.getByRole('tooltip')).toHaveText('联系与交流');
});

test('information and gear settings have separate dialogs', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button', { name: '信息', exact: true }).click();
  const info = page.getByRole('dialog', { name: '信息', exact: true });
  await expect(info).toBeVisible();
  await expect(info).toContainText('连接状态');
  await expect(info).toContainText('数据与安全');
  await info.getByRole('button', { name: '关闭信息' }).click();
  await page.getByRole('button', { name: '设置', exact: true }).click();
  const settings = page.getByRole('dialog', { name: '设置', exact: true });
  await expect(settings).toBeVisible();
  await expect(settings).toContainText('软件更新');
  await expect(settings).not.toContainText('连接状态');
  await settings.getByRole('button', { name: '关闭设置' }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(page.getByRole('button', { name: '设置', exact: true })).toBeFocused();
  await expect(page.getByRole('tooltip')).toHaveCount(0);
});

import { test, expect } from '@playwright/test';

test('shared dark select supports mouse, keyboard, dismissal and persistence', async ({ page }) => {
  await page.goto('/');
  await expect(page.locator('select')).toHaveCount(0);
  const game = page.getByRole('combobox', { name: '选择游戏' });
  await game.click();
  const list = page.getByRole('listbox');
  await expect(list).toBeVisible();
  expect(await list.evaluate(element => element.parentElement === document.body)).toBe(true);
  await expect(page.getByRole('option', { name: '饥荒联机版', exact: true })).toHaveAttribute('aria-selected', 'true');
  await page.keyboard.press('Escape');
  await expect(list).toHaveCount(0);
  await expect(game).toBeFocused();
  await game.press('ArrowDown');
  await game.press('End');
  await game.press('Enter');
  await expect(game).toHaveText('饥荒 · 单机版');
  await game.click();
  await page.getByRole('option', { name: '饥荒联机版', exact: true }).click();
  await expect(game).toHaveText('饥荒联机版');
  await page.getByRole('button', { name: /四季的信笺 · Seasons/ }).click();
  const visibility = page.getByRole('combobox', { name: '可见性', exact: true });
  await visibility.scrollIntoViewIfNeeded();
  await visibility.press('Enter');
  await expect(list).toBeVisible();
  await expect(list.getByRole('option')).toHaveCount(4);
  const box = await list.boundingBox();
  expect(box!.y).toBeGreaterThanOrEqual(8);
  expect(box!.y + box!.height).toBeLessThanOrEqual(1000);
  await visibility.press('End');
  await visibility.press('Enter');
  await expect(visibility).toHaveText('不公开列出');
  await page.getByRole('button', { name: '保存草稿' }).click();
  await page.reload();
  await expect(visibility).toHaveText('不公开列出');
  await visibility.scrollIntoViewIfNeeded();
  await visibility.click();
  await visibility.press('Tab');
  await expect(list).toHaveCount(0);
  await game.click();
  await page.getByRole('heading', { name: 'Workshop Studio' }).click();
  await expect(list).toHaveCount(0);
});
